// Generates src/lib/geo/indonesia.ts: SVG outlines of Indonesia and its
// neighbours from Natural Earth (public domain, via world-atlas).
//
// The map is a plain equirectangular projection so the browser can place a
// point with two multiplications and needs no map library or WebGL.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { feature } from 'topojson-client';

const require = createRequire(import.meta.url);
const world = JSON.parse(readFileSync(require.resolve('world-atlas/countries-50m.json'), 'utf8'));

const LON0 = 94.5;
const LAT0 = 7.5;
const LON1 = 141.5;
const LAT1 = -11.5;
const K = 20; // pixels per degree

const INDONESIA = '360';
const NEIGHBOURS = ['458', '096', '702', '626', '598', '608', '764']; // MY, BN, SG, TL, PG, PH, TH

const project = ([lon, lat]) => [(lon - LON0) * K, (LAT0 - lat) * K];
const inView = ([lon, lat]) => lon >= LON0 - 1 && lon <= LON1 + 1 && lat <= LAT0 + 1 && lat >= LAT1 - 1;

function ringPath(ring) {
	const out = [];
	let last = '';
	for (const point of ring) {
		const [x, y] = project(point);
		const text = `${x.toFixed(1)},${y.toFixed(1)}`;
		if (text !== last) out.push(text);
		last = text;
	}
	// Islands that collapse to a dot at this scale are not worth their bytes
	return out.length >= 4 ? `M${out.join('L')}Z` : '';
}

function countryPath(id) {
	const geo = feature(world, world.objects.countries).features.find((f) => f.id === id);
	if (!geo) throw new Error(`country ${id} not found`);
	const polygons = geo.geometry.type === 'Polygon' ? [geo.geometry.coordinates] : geo.geometry.coordinates;
	return polygons
		.filter((polygon) => polygon[0].some(inView))
		.map((polygon) => polygon.map(ringPath).join(''))
		.join('');
}

const indonesia = countryPath(INDONESIA);
const neighbours = NEIGHBOURS.map(countryPath).join('');

writeFileSync(
	new URL('../src/lib/geo/indonesia.ts', import.meta.url),
	`// Generated by scripts/generate-map.mjs from Natural Earth 1:50m. Do not edit.

/** Equirectangular frame shared by the outline paths and project(). */
export const MAP = { width: ${(LON1 - LON0) * K}, height: ${(LAT0 - LAT1) * K}, lon0: ${LON0}, lat0: ${LAT0}, k: ${K} } as const;

export const INDONESIA_PATH =
	'${indonesia}';

export const NEIGHBOURS_PATH =
	'${neighbours}';
`
);
console.log(`indonesia ${(indonesia.length / 1024).toFixed(1)} KB, neighbours ${(neighbours.length / 1024).toFixed(1)} KB`);
